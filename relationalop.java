public class relationalop {
    public static void main(String[]args){
        int x=50;
        int y=25;
        System.out.println(x==y);
        System.out.println(x!=y);
        System.out.println(x<y);
        System.out.println(x>y);
        System.out.println(x>=y);
        System.out.println(x<=y);
    }
    
}
